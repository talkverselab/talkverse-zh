# === 검증 ===
def is_cjk(c):
    return ord(c) >= 0x4E00

all_used = set()
problems = []
for entry in P:
    pid, key, label, expl, sents = entry
    for zh, py, ko in entry[4]:
        for ch in zh:
            if is_cjk(ch):
                all_used.add(ch)
                if ch not in S:
                    problems.append((pid, zh, ch))

# 4단계 분할 — 각 10 패턴
STAGE_BOUNDS = [
    (1, '인칭·지시·의문·부정·정도(1)', 0, 10),       # p01-p10
    (2, '정도(2)·범위·시간(1)',          10, 20),      # p11-p20
    (3, '시간(2)·전치사',                 20, 30),      # p21-p30
    (4, '조동사·접속',                    30, 40),      # p31-p40
]
def stage_of(idx):
    for s, _, lo, hi in STAGE_BOUNDS:
        if lo <= idx < hi:
            return s
    return 1

print(f"패턴: {len(P)}")
print(f"문장: {sum(len(p[4]) for p in P)}")
print(f"단계: {len(STAGE_BOUNDS)}")
print(f"사용 한자 (unique): {len(all_used)}")
print(f"S1+S2 셋 크기: {len(S)}")
print()
