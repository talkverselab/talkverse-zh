TOTAL = len(L2)
STAGE_BOUNDS = [
    (1, '어기조사 (1)',            0, 10),       # 어기조사 10
    (2, '부사 (1)',                10, 22),       # 부사 12
    (3, '부사 (2) + 필수 단어 핵심', 22, 45),       # 부사 10 + 단어 핵심 13
    (4, '필수 단어 확장',           45, TOTAL),   # 나머지
]
def stage_of(i):
    for s, _, lo, hi in STAGE_BOUNDS:
        if lo <= i < hi:
            return s
    return 4

